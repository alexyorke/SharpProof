using static SharpProof.CompilerProbe.TestAsset.CompilerProbeSourceHelpers;

namespace SharpProof.CompilerProbe.TestAsset;

[Generator(LanguageNames.CSharp)]
public sealed class CompilerProbeGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        RepositoryParameterGuard.RequireInitialized(context.Equals(default(IncrementalGeneratorInitializationContext)), nameof(context), "Value must be initialized.");

        var globalValue = context.AnalyzerConfigOptionsProvider.Select(
            static (provider, _) => provider is null ? throw new System.ArgumentNullException(nameof(provider)) : (GetOption(
                provider.GlobalOptions,
                CompilerProbeContract.GlobalValueOptionKey)));
        var inputs = context.AdditionalTextsProvider
            .Where(static file =>
                file is null ? throw new System.ArgumentNullException(nameof(file)) : (string.Equals(
                    Path.GetFileName(file.Path),
                    CompilerProbeContract.AdditionalFileName,
                    StringComparison.OrdinalIgnoreCase)))
            .Collect()
            .Combine(context.AnalyzerConfigOptionsProvider)
            .Select(static (pair, cancellationToken) =>
            {
                var files = pair.Left;
                if (files.IsDefaultOrEmpty)
                {
                    return ImmutableArray<(
                        string Path,
                        string Text,
                        string Metadata)>.Empty;
                }

                var selected = files[0];
                var selectedPath = NormalizePath(selected.Path);
                for (var index = 1; index < files.Length; index++)
                {
                    cancellationToken.ThrowIfCancellationRequested();
                    var candidate = files[index];
                    var candidatePath = NormalizePath(candidate.Path);
                    if (StringComparer.Ordinal.Compare(
                            candidatePath,
                            selectedPath) < 0)
                    {
                        selected = candidate;
                        selectedPath = candidatePath;
                    }
                }

                var text = selected.GetText(cancellationToken)?.ToString() ??
                    string.Empty;
                var metadata = GetOption(
                    pair.Right.GetOptions(selected),
                    CompilerProbeContract.AdditionalFileMetadataOptionKey);
                return ImmutableArray.Create((
                    Path: selectedPath,
                    Text: text,
                    Metadata: metadata));
            });
        context.RegisterSourceOutput(
            globalValue.Combine(inputs),
            static (productionContext, input) =>
                { RepositoryParameterGuard.RequireInitialized((productionContext.Equals(default(SourceProductionContext))), nameof(productionContext), "Value must be initialized."); Generate(productionContext, input.Left, input.Right); });
    }

    private static void Generate(
        SourceProductionContext context,
        string globalValue,
        ImmutableArray<(string Path, string Text, string Metadata)> inputs)
    {
        RepositoryParameterGuard.RequireInitialized(context.Equals(default(SourceProductionContext)), nameof(context), "Value must be initialized.");

        globalValue = RepositoryParameterGuard.NotNull(globalValue, nameof(globalValue));
        if (inputs.IsDefaultOrEmpty)
        {
            return;
        }

        var input = inputs[0];
        var fingerprint = ProbeHash.Text(
            globalValue + "\0" + input.Metadata + "\0" + input.Text);
        context.AddSource(
            CompilerProbeContract.GlobalUsingsHintName,
            SourceText.From(
                """
                // <auto-generated/>
                global using SharpProof.CompilerProbe.Generated;
                """,
                Encoding.UTF8));
        context.AddSource(
            CompilerProbeContract.ContractHintName,
            SourceText.From(
                CreateContractSource(
                    input.Path,
                    input.Text,
                    input.Metadata,
                    globalValue,
                    fingerprint),
                Encoding.UTF8));
    }

    private static string CreateContractSource(
        string path,
        string text,
        string metadata,
        string globalValue,
        string fingerprint)
    {
        fingerprint = RepositoryParameterGuard.NotNull(fingerprint, nameof(fingerprint));
        globalValue = RepositoryParameterGuard.NotNull(globalValue, nameof(globalValue));
        metadata = RepositoryParameterGuard.NotNull(metadata, nameof(metadata));
        path = RepositoryParameterGuard.NotNull(path, nameof(path));
        text = RepositoryParameterGuard.NotNull(text, nameof(text));
        var postconditionOperator = text.StartsWith(
            "refute:",
            StringComparison.Ordinal)
            ? "!="
            : "==";
        return $$"""
        // <auto-generated/>
        #nullable enable
        namespace SharpProof.CompilerProbe.Generated {
            public static class ProbeGenerated {
                public const string InputPath = {{Literal(path)}};
                public const string InputText = {{Literal(text)}};
                public const string MetadataValue = {{Literal(metadata)}};
                public const string GlobalValue = {{Literal(globalValue)}};
                public const string InputFingerprint = {{Literal(fingerprint)}};

                public static int Verify(int value) {
                    global::SharpProof.Attributes.Contract.Requires(value >= 0);
                    global::SharpProof.Attributes.Contract.Ensures(
                        global::SharpProof.Attributes.Contract.Result<int>() {{postconditionOperator}} value);
                    return value;
                }
            }
        }
        """;
    }

    private static string Literal(string value)
    {
        value = RepositoryParameterGuard.NotNull(value, nameof(value));
        return Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(
            value,
            quote: true);
    }

}
