    private const string ExpectedContentSha256 =
        "c0f4a6b09d7efdb66ac11457ae4d80345c9a977286118058ae67750961a3342e";

    [Test]
    public void GeneratedCatalogPreservesEveryReviewedWitness()
    {
        using var document = JsonDocument.Parse(
            File.ReadAllText(CatalogPath()));
        var root = document.RootElement;
        Assert.That(
            root.GetProperty("schema").GetString(),
            Is.EqualTo("SharpProof.ApiSpecCatalog"));
        Assert.That(
            root.GetProperty("schemaVersion").GetInt32(),
            Is.EqualTo(1));
        Assert.That(
            ApiSpecTable.DefaultTableIdentity,
            Is.EqualTo(root.GetProperty("tableIdentity").GetString()));
        Assert.That(
            ApiSpecTable.DefaultTableVersion,
            Is.EqualTo(root.GetProperty("tableVersion").GetString()));

        var assemblies = ReadAssemblySets(root);
        var evidence = ReadEvidence(root);
        var reviewed = root.GetProperty("declarations")
            .EnumerateArray()
            .OrderBy(static declaration =>
                declaration.GetProperty("target")
                    .GetProperty("witnessIdentifier").GetString(),
                StringComparer.Ordinal)
            .ToArray();
        var templates = ApiSpecTable.Default.Templates;
        Assert.That(
            templates.Select(static template =>
                template.Target.WitnessIdentifier),
            Is.EqualTo(reviewed.Select(static declaration =>
                declaration.GetProperty("target")
                    .GetProperty("witnessIdentifier").GetString())));

        for (var index = 0; index < reviewed.Length; index++)
        {
            AssertDeclaration(
                reviewed[index],
                templates[index],
                assemblies,
                evidence);
        }
        Assert.That(
            ApiSpecTable.Default.ContentSha256,
            Is.EqualTo(ExpectedContentSha256));
    }

