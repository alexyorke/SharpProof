    [Test]
    public async Task GeneratorRejectsDuplicateJsonProperties()
    {
        using var workspace = GenerationWorkspace.Create();
        var catalog = await File.ReadAllTextAsync(CatalogPath());
        var variants = new[]
        {
            catalog.Replace(
                "  \"tableVersion\": \"5\",",
                "  \"tableVersion\": \"5\",\n  \"tableVersion\": \"shadow\",",
                StringComparison.Ordinal),
            catalog.Replace(
                "        \"nullness\": {\n          \"result\": \"NonNull\",",
                "        \"nullness\": {\n          \"result\": \"NonNull\",\n          \"result\": \"Null\",",
                StringComparison.Ordinal)
        };

        foreach (var variant in variants)
        {
            await File.WriteAllTextAsync(
                workspace.CatalogInputPath,
                variant,
                new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
            var result = await RunGeneratorAsync(
                "-CatalogPath",
                workspace.CatalogInputPath,
                "-SourceOutputPath",
                workspace.FirstSourcePath,
                "-DocumentationOutputPath",
                workspace.FirstDocumentationPath,
                "-RuntimeWitnessOutputPath",
                workspace.FirstRuntimeWitnessPath);

            Assert.That(result.ExitCode, Is.Not.Zero, result.Output);

            var runtimeResult = await RunRuntimeWitnessGeneratorAsync(
                "-CatalogPath",
                workspace.CatalogInputPath,
                "-OutputPath",
                workspace.FirstRuntimeWitnessPath);
            Assert.That(runtimeResult.ExitCode, Is.Not.Zero, runtimeResult.Output);
        }
    }

    private static void AssertDeclaration(
        JsonElement declaration,
        ApiSpecTemplate template,
        Dictionary<string, ApiSpecAssemblyIdentity[]> assemblies,
        Dictionary<string, SpecEvidence> evidence)
    {
        var expected = declaration.GetProperty("target");
        var actual = template.Target;
        var witness = actual.WitnessIdentifier;
        Assert.Multiple(() =>
        {
            Assert.That(
                actual.WitnessIdentifier,
                Is.EqualTo(
                    expected.GetProperty("witnessIdentifier").GetString()),
                witness);
            Assert.That(
                actual.DocumentationCommentId,
                Is.EqualTo(
                    expected.GetProperty("documentationCommentId").GetString()),
                witness);
            Assert.That(
                actual.ContainingTypeMetadataName,
                Is.EqualTo(
                    expected.GetProperty(
                        "containingTypeMetadataName").GetString()),
                witness);
            Assert.That(
                actual.MemberKind,
                Is.EqualTo(
                    EnumValue<SpecTargetMemberKind>(
                        expected.GetProperty("memberKind"))),
                witness);
            Assert.That(
                actual.MemberName,
                Is.EqualTo(
                    expected.GetProperty("memberName").GetString()),
                witness);
            Assert.That(
                actual.IsStatic,
                Is.EqualTo(expected.GetProperty("isStatic").GetBoolean()),
                witness);
            Assert.That(
                actual.GenericArity,
                Is.EqualTo(
                    expected.GetProperty("genericArity").GetInt32()),
                witness);
            Assert.That(
                actual.ReceiverType,
                Is.EqualTo(
                    NullableEnumValue<IrTypeKind>(
                        expected.GetProperty("receiverType"))),
                witness);
            Assert.That(
                actual.ParameterTypes,
                Is.EqualTo(expected.GetProperty("parameterTypes")
                    .EnumerateArray()
                    .Select(EnumValue<IrTypeKind>)
                    .ToArray()),
                witness);
            Assert.That(
                actual.ResultType,
                Is.EqualTo(
                    NullableEnumValue<IrTypeKind>(
                        expected.GetProperty("resultType"))),
                witness);
            var assemblySet = expected
                .GetProperty("approvedAssemblySet").GetString() ??
                throw new InvalidDataException(
                    "An approved assembly set is null.");
            Assert.That(
                actual.ApprovedAssemblies,
                Is.EqualTo(assemblies[assemblySet]),
                witness);
        });

        AssertFacets(
            declaration.GetProperty("facets"),
            template.Facets,
            evidence,
            witness);
        var postconditions = declaration.GetProperty("postconditions")
            .EnumerateArray()
            .ToArray();
        Assert.That(
            template.Postconditions,
            Has.Length.EqualTo(postconditions.Length),
            witness);
        for (var index = 0;
             index < postconditions.Length;
             index++)
        {
            var expectedPostcondition = postconditions[index];
            var actualPostcondition = template.Postconditions[index];
            Assert.That(
                Describe(actualPostcondition.Condition),
                Is.EqualTo(
                    Describe(
                        expectedPostcondition.GetProperty("condition"))),
                witness + " postcondition " + index);
            Assert.That(
                actualPostcondition.Evidence,
                Is.EqualTo(
                    Evidence(
                        expectedPostcondition.GetProperty("evidence"),
                        evidence)),
                witness + " postcondition " + index);
        }
    }

    private static void AssertFacets(
        JsonElement expected,
        ApiSpecFacets actual,
        Dictionary<string, SpecEvidence> evidence,
        string witness)
    {
        var effects = expected.GetProperty("effects");
        var expectedEffects = effects.GetProperty("values")
            .EnumerateArray()
            .Aggregate(
                SpecEffect.None,
                static (value, element) =>
                    value | EnumValue<SpecEffect>(element));
        var allocation = expected.GetProperty("allocation");
        var throws = expected.GetProperty("throws");
        var nullness = expected.GetProperty("nullness");
        var cardinality = expected.GetProperty("cardinality");
        var exactCount = cardinality.GetProperty("exactCount");
        Assert.Multiple(() =>
        {
            Assert.That(
                actual.Effects.Effects,
                Is.EqualTo(expectedEffects),
                witness);
            Assert.That(
                actual.Effects.Evidence,
                Is.EqualTo(
                    Evidence(effects.GetProperty("evidence"), evidence)),
                witness);
            Assert.That(
                actual.Allocation.Behavior,
                Is.EqualTo(
                    EnumValue<SpecAllocationBehavior>(
                        allocation.GetProperty("behavior"))),
                witness);
            Assert.That(
                actual.Allocation.Evidence,
                Is.EqualTo(
                    Evidence(
                        allocation.GetProperty("evidence"),
                        evidence)),
                witness);
            Assert.That(
                actual.Throws.Behavior,
                Is.EqualTo(
                    EnumValue<SpecThrowBehavior>(
                        throws.GetProperty("behavior"))),
                witness);
            Assert.That(
                actual.Throws.ExceptionMetadataNames,
                Is.EqualTo(
                    throws.GetProperty("exceptionMetadataNames")
                        .EnumerateArray()
                        .Select(static item => item.GetString())
                        .ToArray()),
                witness);
            Assert.That(
                actual.Throws.Evidence,
                Is.EqualTo(
                    Evidence(throws.GetProperty("evidence"), evidence)),
                witness);
            Assert.That(
                actual.Nullness.Result,
                Is.EqualTo(
                    EnumValue<SpecNullness>(
                        nullness.GetProperty("result"))),
                witness);
            Assert.That(
                actual.Nullness.Evidence,
                Is.EqualTo(
                    Evidence(
                        nullness.GetProperty("evidence"),
                        evidence)),
                witness);
            Assert.That(
                actual.Cardinality.Result,
                Is.EqualTo(
                    EnumValue<SpecCardinality>(
                        cardinality.GetProperty("result"))),
                witness);
            Assert.That(
                actual.Cardinality.ExactCount,
                Is.EqualTo(
                    exactCount.ValueKind == JsonValueKind.Null
                        ? null
                        : exactCount.GetInt32()),
                witness);
            Assert.That(
                actual.Cardinality.Evidence,
                Is.EqualTo(
                    Evidence(
                        cardinality.GetProperty("evidence"),
                        evidence)),
                witness);
        });

        if (expected.TryGetProperty("termination", out var termination))
        {
            Assert.That(actual.Termination, Is.Not.Null, witness);
            Assert.Multiple(() =>
            {
                Assert.That(
                    actual.Termination!.Behavior,
                    Is.EqualTo(
                        EnumValue<SpecTerminationBehavior>(
                            termination.GetProperty("behavior"))),
                    witness);
                Assert.That(
                    actual.Termination.Evidence,
                    Is.EqualTo(
                        Evidence(
                            termination.GetProperty("evidence"),
                            evidence)),
                    witness);
            });
        }
        else
        {
            Assert.That(actual.Termination, Is.Null, witness);
        }
    }

    private static Dictionary<string, ApiSpecAssemblyIdentity[]>
        ReadAssemblySets(JsonElement root)
    {
        var result =
            new Dictionary<string, ApiSpecAssemblyIdentity[]>(
                StringComparer.Ordinal);
        foreach (var set in root.GetProperty("assemblySets")
                     .EnumerateArray())
        {
            var id = set.GetProperty("id").GetString() ??
                throw new InvalidDataException(
                    "An assembly set id is null.");
            var identities = set.GetProperty("identities").EnumerateArray()
                .SelectMany(static identity =>
                    identity.GetProperty("referenceFamilies").EnumerateArray()
                        .Select(family => new ApiSpecAssemblyIdentity(
                            identity.GetProperty("name").GetString() ??
                            throw new InvalidDataException("An assembly name is null."),
                            identity.GetProperty("publicKeyToken").GetString() ??
                            throw new InvalidDataException("A public-key token is null."),
                            Enum.Parse<ApiSpecReferenceFamily>(
                                family.GetString() ??
                                throw new InvalidDataException(
                                    "A reference family is null.")))))
                .ToArray();
            result.Add(id, identities);
        }
        return result;
    }

    private static Dictionary<string, SpecEvidence> ReadEvidence(
        JsonElement root)
    {
        return root.GetProperty("evidence")
            .EnumerateArray()
            .ToDictionary(
                static item => item.GetProperty("id").GetString() ??
                    throw new InvalidDataException(
                        "An evidence id is null."),
                static item => new SpecEvidence(
                    EnumValue<SpecEvidenceKind>(
                        item.GetProperty("kind")),
                    item.GetProperty("source").GetString() ??
                    throw new InvalidDataException(
                        "An evidence source is null.")),
                StringComparer.Ordinal);
    }

    private static SpecEvidence Evidence(
        JsonElement reference,
        Dictionary<string, SpecEvidence> evidence)
    {
        var id = reference.GetString() ??
            throw new InvalidDataException(
                "An evidence reference is null.");
        return evidence[id];
    }

    private static string Describe(JsonElement term)
    {
        var kind = term.GetProperty("kind").GetString();
        var type = term.GetProperty("type").GetString();
        return kind switch
        {
            "variable" =>
                "variable:" +
                term.GetProperty("role").GetString() + ":" +
                term.GetProperty("ordinal").GetInt32() + ":" + type,
            "boolean" =>
                "boolean:" +
                term.GetProperty("value").GetBoolean() + ":" + type,
            "integer" =>
                "integer:" +
                term.GetProperty("value").GetInt64() + ":" + type,
            "string" =>
                "string:" +
                JsonSerializer.Serialize(
                    term.GetProperty("value").GetString()) + ":" + type,
            "null" => "null:" + type,
            "unary" =>
                "unary:" +
                term.GetProperty("operator").GetString() + ":" + type +
                "(" + Describe(term.GetProperty("operand")) + ")",
            "binary" =>
                "binary:" +
                term.GetProperty("operator").GetString() + ":" + type +
                "(" + Describe(term.GetProperty("left")) + "," +
                Describe(term.GetProperty("right")) + ")",
            "conditional" =>
                "conditional:" + type +
                "(" + Describe(term.GetProperty("condition")) + "," +
                Describe(term.GetProperty("whenTrue")) + "," +
                Describe(term.GetProperty("whenFalse")) + ")",
            "length" =>
                "length:" + type +
                "(" + Describe(term.GetProperty("value")) + ")",
            _ => throw new InvalidDataException(
                "Unknown catalog term kind: " + kind)
        };
    }

    private static string Describe(SpecTermDeclaration term)
    {
        return term switch
        {
            SpecVariableDeclaration variable =>
                "variable:" + variable.Role + ":" + variable.Ordinal + ":" + variable.Type,
            SpecBooleanDeclaration boolean =>
                "boolean:" + boolean.Value + ":" + boolean.Type,
            SpecIntegerDeclaration integer =>
                "integer:" + integer.Value + ":" + integer.Type,
            SpecStringDeclaration text =>
                "string:" + JsonSerializer.Serialize(text.Value) +
                ":" + text.Type,
            SpecNullDeclaration nullTerm =>
                "null:" + nullTerm.Type,
            SpecUnaryDeclaration unary =>
                "unary:" + unary.Operator + ":" + unary.Type +
                "(" + Describe(unary.Operand) + ")",
            SpecBinaryDeclaration binary =>
                "binary:" + binary.Operator + ":" + binary.Type +
                "(" + Describe(binary.Left) + "," +
                Describe(binary.Right) + ")",
            SpecConditionalDeclaration conditional =>
                "conditional:" + conditional.Type +
                "(" + Describe(conditional.Condition) + "," +
                Describe(conditional.WhenTrue) + "," +
                Describe(conditional.WhenFalse) + ")",
            SpecLengthDeclaration length =>
                "length:" + length.Type +
                "(" + Describe(length.Value) + ")",
            _ => throw new ArgumentOutOfRangeException(nameof(term))
        };
    }

    private static T EnumValue<T>(JsonElement value)
        where T : struct, Enum
    {
        return Enum.Parse<T>(
            value.GetString() ??
            throw new InvalidDataException(
                "An enum value is null."),
            ignoreCase: false);
    }

    private static T? NullableEnumValue<T>(JsonElement value)
        where T : struct, Enum
    {
        return value.ValueKind == JsonValueKind.Null
            ? null
            : EnumValue<T>(value);
    }

    private static void AssertGeneratedEncoding(
        byte[] bytes,
        string expectedHeader)
    {
        Assert.That(bytes, Is.Not.Empty);
        Assert.That(
            bytes.Length >= 3 &&
            bytes[0] == 0xEF &&
            bytes[1] == 0xBB &&
            bytes[2] == 0xBF,
            Is.False);
        var text = Encoding.UTF8.GetString(bytes);
        Assert.That(text, Does.StartWith(expectedHeader));
        Assert.That(text, Does.Not.Contain('\r'));
        Assert.That(text, Does.EndWith("\n"));
    }

    private static async Task<GeneratorResult> RunGeneratorAsync(
