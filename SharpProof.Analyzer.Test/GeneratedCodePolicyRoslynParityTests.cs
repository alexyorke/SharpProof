using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using NUnit.Framework;

namespace SharpProof.Analyzer.Test;

[TestFixture]
public sealed class GeneratedCodePolicyRoslynParityTests
{
    [TestCase("// <auto-generated>\n// generated body\n// </auto-generated>\n")]
    [TestCase("// License header.\n// <auto-generated />\n")]
    [TestCase("/* <autogenerated by the source generator */\n")]
    public async Task HeaderClassificationMatchesRoslyn(
        string header)
    {
        var compilation = AnalyzerTestHost.CreateCompilation(
            header + "internal static class Subject { internal static void Run() { } }",
            [],
            filePath: "Subject.cs");
        var tree = compilation.SyntaxTrees.Single();
        var probe = new RoslynGeneratedCodeProbe();
        var withAnalyzers = compilation.WithAnalyzers(
            [probe],
            new CompilationWithAnalyzersOptions(
                new AnalyzerOptions([]),
                onAnalyzerException: null,
                concurrentAnalysis: false,
                logAnalyzerExecutionTime: false));

        _ = await withAnalyzers.GetAnalyzerDiagnosticsAsync();

        var roslynGenerated = probe.Get();
        Assert.That(roslynGenerated, Is.True);
        Assert.That(
            AnalyzerGeneratedCodePolicy.IsGenerated(
                tree,
                compilation,
                CancellationToken.None),
            Is.EqualTo(roslynGenerated));
    }

#pragma warning disable RS1001, RS1036, RS1041, RS2008
    [DiagnosticAnalyzer(LanguageNames.CSharp)]
    private sealed class RoslynGeneratedCodeProbe : DiagnosticAnalyzer
    {
        private static readonly DiagnosticDescriptor ProbeDescriptor =
            new(
                "SPTEST001",
                "Generated code probe",
                "Generated code probe",
                "Tests",
                DiagnosticSeverity.Hidden,
                isEnabledByDefault: true);
        private bool? result;

        public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics =>
            [ProbeDescriptor];

        public override void Initialize(AnalysisContext context)
        {
            context.ConfigureGeneratedCodeAnalysis(
                GeneratedCodeAnalysisFlags.Analyze |
                GeneratedCodeAnalysisFlags.ReportDiagnostics);
            context.EnableConcurrentExecution();
            context.RegisterSyntaxTreeAction(context =>
            {
                result = context.IsGeneratedCode;
                context.ReportDiagnostic(Diagnostic.Create(
                    ProbeDescriptor,
                    context.Tree.GetRoot(context.CancellationToken).GetLocation()));
            });
        }

        internal bool Get()
        {
            return result ?? throw new AssertionException(
                "Roslyn did not invoke the generated-code probe.");
        }
    }
#pragma warning restore RS1001, RS1036, RS1041, RS2008
}
