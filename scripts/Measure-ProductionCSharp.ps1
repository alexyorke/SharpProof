[CmdletBinding()]
param(
    [Parameter()][switch]$Json
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$baselineCommit = '0397caa789231b6ce8a49edd7eb15e6be14b7190'
$baselinePhysicalLines = 30888
$baselineNonblankLines = 30797
$maximumPhysicalLines = 20888
$maximumNonblankLines = 20797
$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$roots = @(
    'SharpProof.Attributes/',
    'SharpProof.Analyzer/',
    'SharpProof.Package/',
    'SharpProof.ProofCore/',
    'SharpProof.Symbolic/',
    'Tools/SharpProof.SymbolicCli/'
)
$generatedFileNamePattern = '\.(g|generated)\.cs$'
$autoGeneratedHeaderPattern = '(?im)^\s*//\s*<auto-generated(?:\s*/>|>)'

Push-Location $repoRoot
try
{
    $paths = @(git ls-files --cached --others --exclude-standard -- '*.cs')
    if ($LASTEXITCODE -ne 0) { throw 'git ls-files failed.' }
    $files = @($paths | Where-Object {
        $path = $_.Replace('\', '/')
        (Test-Path -LiteralPath $path) -and
            @($roots | Where-Object { $path.StartsWith($_, [StringComparison]::Ordinal) }).Count -ne 0
    })
    $physicalLineCount = 0
    $lineCount = 0
    $handwrittenFiles = 0
    foreach ($path in $files)
    {
        $source = Get-Content -LiteralPath $path -Raw
        if ($path -match $generatedFileNamePattern -or
            $source -match $autoGeneratedHeaderPattern) { continue }
        $lines = @(Get-Content -LiteralPath $path)
        $physicalLineCount += $lines.Count
        $lineCount += @($lines | Where-Object { -not [string]::IsNullOrWhiteSpace($_) }).Count
        $handwrittenFiles++
    }
    $removedPhysicalLines = $baselinePhysicalLines - $physicalLineCount
    $removedNonblankLines = $baselineNonblankLines - $lineCount
    $physicalPassed = $physicalLineCount -le $maximumPhysicalLines
    $nonblankPassed = $lineCount -le $maximumNonblankLines
    $result = [ordered]@{
        schemaVersion = 2
        baselineCommit = $baselineCommit
        baselinePhysicalLines = $baselinePhysicalLines
        baselineNonblankLines = $baselineNonblankLines
        maximumPhysicalLines = $maximumPhysicalLines
        maximumNonblankLines = $maximumNonblankLines
        roots = $roots
        exclusions = [ordered]@{
            generatedFileNamePattern = $generatedFileNamePattern
            autoGeneratedHeaderPattern = $autoGeneratedHeaderPattern
        }
        files = $handwrittenFiles
        physicalLines = $physicalLineCount
        nonblankLines = $lineCount
        removedPhysicalLines = $removedPhysicalLines
        removedNonblankLines = $removedNonblankLines
        creditedRemovedLines = [Math]::Min($removedPhysicalLines, $removedNonblankLines)
        physicalPassed = $physicalPassed
        nonblankPassed = $nonblankPassed
        passed = $physicalPassed -and $nonblankPassed
    }
    if ($Json) { $result | ConvertTo-Json -Depth 4 }
    else
    {
        "Production C# files: $handwrittenFiles"
        "Production C# nonblank lines: $lineCount"
        "Production C# physical lines: $physicalLineCount"
        "Nonblank lines removed from baseline: $removedNonblankLines"
        "Physical lines removed from baseline: $removedPhysicalLines"
        "Credited lines removed: $($result.creditedRemovedLines)"
        "Target maximum nonblank lines: $maximumNonblankLines"
        "Target maximum physical lines: $maximumPhysicalLines"
    }
    if (-not $result.passed) { exit 1 }
}
finally
{
    Pop-Location
}
