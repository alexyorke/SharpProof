[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'SharpProof.CSharpFormatting.psm1') -Force

function Assert-FormattingFailure([scriptblock]$Action, [string]$Message) {
    try { & $Action }
    catch {
        if ($_.Exception.Message -notlike "*$Message*") { throw }
        return
    }
    throw "Formatting control unexpectedly accepted: $Message"
}

function Write-FormattingFixture([string]$Root, [string]$Path, [string]$Text) {
    $destination = Join-Path $Root $Path
    [void][IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($destination))
    [IO.File]::WriteAllText($destination, $Text, [Text.UTF8Encoding]::new($false))
}

$fixture = Join-Path ([IO.Path]::GetTempPath()) ('sharpproof-format-control-' + [Guid]::NewGuid().ToString('N'))
$savedEnvironment = [ordered]@{}
foreach ($name in @('GITHUB_SHA', 'GITHUB_RUN_ID', 'GITHUB_RUN_ATTEMPT', 'SHARPPROOF_FORMAT_ARTIFACT_ATTEMPTS')) {
    $savedEnvironment[$name] = [Environment]::GetEnvironmentVariable($name)
}
try {
    [void][IO.Directory]::CreateDirectory($fixture)
    Write-FormattingFixture $fixture 'SharpProof.slnx' @'
<Solution>
  <Project Path="src/SharpProof.Worker.Tests/SharpProof.Worker.Tests.csproj" />
  <Project Path="src/Other/Other.csproj" />
</Solution>
'@
    $projectText = @'
<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup><TargetFramework>net10.0</TargetFramework></PropertyGroup>
  <ItemGroup>
    <Compile Include="../../shared/Linked.cs" Link="Linked.cs" />
    <AdditionalFiles Include="../../shared/rules.txt" />
  </ItemGroup>
</Project>
'@
    Write-FormattingFixture $fixture 'src/SharpProof.Worker.Tests/SharpProof.Worker.Tests.csproj' $projectText
    Write-FormattingFixture $fixture 'src/Other/Other.csproj' $projectText
    Write-FormattingFixture $fixture 'src/SharpProof.Worker.Tests/Worker.cs' "internal sealed class Worker { }`n"
    Write-FormattingFixture $fixture 'src/Other/Other.cs' "internal sealed class Other { }`n"
    Write-FormattingFixture $fixture 'shared/Linked.cs' "// <auto-generated/>`ninternal sealed class Linked { }`n"
    Write-FormattingFixture $fixture 'shared/rules.txt' "additional-file-content`n"
    Write-FormattingFixture $fixture 'outside directory/space file.cs' "internal sealed class Outside { }`n"
    & git -C $fixture init --quiet
    if ($LASTEXITCODE -ne 0) { throw 'Formatting fixture Git initialization failed.' }
    & git -C $fixture add --all
    if ($LASTEXITCODE -ne 0) { throw 'Formatting fixture source staging failed.' }
    & git -C $fixture -c user.name=SharpProof -c user.email=fixture@example.invalid commit --quiet --no-gpg-sign -m 'Formatting fixture'
    if ($LASTEXITCODE -ne 0) { throw 'Formatting fixture source snapshot failed.' }
    $env:GITHUB_SHA = [string](& git -C $fixture rev-parse HEAD)
    if ($LASTEXITCODE -ne 0) { throw 'Formatting fixture commit could not be read.' }
    $env:GITHUB_RUN_ID = '123'
    $env:GITHUB_RUN_ATTEMPT = '2'
    $env:SHARPPROOF_FORMAT_ARTIFACT_ATTEMPTS = '{"0":"2","1":"2"}'

    $plans = @(Get-SharpProofCSharpFormattingPlan -RepositoryRoot $fixture -ShardCount 2 -ShardIndex 0
        Get-SharpProofCSharpFormattingPlan -RepositoryRoot $fixture -ShardCount 2 -ShardIndex 1)
    if ($plans[0].selectedProjects.Count -ne 1 -or
        $plans[0].selectedProjects[0] -cne 'src/SharpProof.Worker.Tests/SharpProof.Worker.Tests.csproj' -or
        $plans[1].selectedProjects.Count -ne 1 -or $plans[1].selectedProjects[0] -cne 'src/Other/Other.csproj' -or
        $plans[0].sourceFiles.Count -ne 4 -or $plans[1].sourceSha256 -cne $plans[0].sourceSha256) {
        throw 'Formatting plans lost complete roots, linked/generated sources, or space-bearing paths.'
    }
    $unsharded = Get-SharpProofCSharpFormattingPlan -RepositoryRoot $fixture
    if ($unsharded.selectedProjects.Count -ne 2 -or $unsharded.sourceSha256 -cne $plans[0].sourceSha256) {
        throw 'Unsharded formatting no longer selects every original root and tracked source.'
    }
    Assert-FormattingFailure { Get-SharpProofCSharpFormattingPlan -RepositoryRoot $fixture -ShardCount 1 -ShardIndex 1 } 'outside its count'
    Assert-FormattingFailure { & (Join-Path $PSScriptRoot 'Format-CSharp.ps1') -ShardCount 2 } 'require verification mode'
    foreach ($plan in $plans) { Write-SharpProofCSharpFormattingReceipt -RepositoryRoot $fixture -Plan $plan }
    Assert-SharpProofCSharpFormattingShards -RepositoryRoot $fixture
    $validation = Get-Content -LiteralPath (Join-Path $fixture 'artifacts/formatting/formatting-validation.json') -Raw | ConvertFrom-Json
    if ($validation.roots -ne 2 -or $validation.sourceFiles -ne 4) { throw 'Formatting aggregate lost complete coverage.' }

    $receiptPath = Join-Path $fixture 'artifacts/formatting/shard-0.json'
    $original = [IO.File]::ReadAllText($receiptPath)
    $mutations = @(
        { param($Receipt) $Receipt.schemaVersion = 2 },
        { param($Receipt) $Receipt.planVersion = 'different' },
        { param($Receipt) $Receipt.formatFlagsVersion = 'without-generated-files' },
        { param($Receipt) $Receipt.solutionSha256 = '0' * 64 },
        { param($Receipt) $Receipt.sourceSha256 = '0' * 64 },
        { param($Receipt) $Receipt.rootProjectsSha256 = '0' * 64 },
        { param($Receipt) $Receipt.identity.commit = '0' * 40 },
        { param($Receipt) $Receipt.identity.tree = '0' * 40 },
        { param($Receipt) $Receipt.identity.runId = '456' },
        { param($Receipt) $Receipt.identity.runAttempt = '1' },
        { param($Receipt) $Receipt.shardCount = 1 },
        { param($Receipt) $Receipt.shardIndex = 1 },
        { param($Receipt) $Receipt.selectedProjects = @() },
        { param($Receipt) $Receipt.selectedProjects = $Receipt.rootProjects },
        { param($Receipt) $Receipt.rootProjects = @($Receipt.rootProjects[0]) },
        { param($Receipt) $Receipt.sourceFiles = @() },
        { param($Receipt) $Receipt.sourceFiles[0].sha256 = '0' * 64 },
        { param($Receipt) $Receipt.sourceFiles[0].path = '../outside.cs' },
        { param($Receipt) $Receipt.unrecognized = $true }
    )
    foreach ($mutation in $mutations) {
        $receipt = $original | ConvertFrom-Json -AsHashtable
        & $mutation $receipt
        $receipt | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath $receiptPath -Encoding utf8NoBOM
        Assert-FormattingFailure { Assert-SharpProofCSharpFormattingShards -RepositoryRoot $fixture } 'receipt differs'
        [IO.File]::WriteAllText($receiptPath, $original, [Text.UTF8Encoding]::new($false))
    }
    foreach ($attempts in @(@{ '0' = '0'; '1' = '2' }, @{ '0' = '3'; '1' = '2' }, @{ '0' = ''; '1' = '2' })) {
        Assert-FormattingFailure { Assert-SharpProofCSharpFormattingShards -RepositoryRoot $fixture -ArtifactAttempts $attempts } 'attempt is invalid'
    }
    Assert-FormattingFailure { Assert-SharpProofCSharpFormattingShards -RepositoryRoot $fixture -ArtifactAttempts @{ '0' = '2' } } 'exactly two producer attempts'
    $prior = $original | ConvertFrom-Json -AsHashtable
    $prior.identity.runAttempt = '1'
    $prior | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath $receiptPath -Encoding utf8NoBOM
    Assert-SharpProofCSharpFormattingShards -RepositoryRoot $fixture -ArtifactAttempts @{ '0' = '1'; '1' = '2' }
    [IO.File]::WriteAllText($receiptPath, $original, [Text.UTF8Encoding]::new($false))

    $extraPath = Join-Path $fixture 'artifacts/formatting/shard-2.json'
    [IO.File]::WriteAllText($extraPath, $original, [Text.UTF8Encoding]::new($false))
    Assert-FormattingFailure { Assert-SharpProofCSharpFormattingShards -RepositoryRoot $fixture } 'exactly two receipts'
    Remove-Item -LiteralPath $extraPath -Force
    $otherPath = Join-Path $fixture 'artifacts/formatting/shard-1.json'
    $otherReceipt = [IO.File]::ReadAllText($otherPath)
    Remove-Item -LiteralPath $otherPath -Force
    Assert-FormattingFailure { Assert-SharpProofCSharpFormattingShards -RepositoryRoot $fixture } 'exactly two receipts'
    [IO.File]::WriteAllText($otherPath, $otherReceipt, [Text.UTF8Encoding]::new($false))
    $sourcePath = Join-Path $fixture 'shared/Linked.cs'
    $sourceText = [IO.File]::ReadAllText($sourcePath)
    [IO.File]::WriteAllText($sourcePath, $sourceText + '// changed', [Text.UTF8Encoding]::new($false))
    Assert-FormattingFailure { Assert-SharpProofCSharpFormattingShards -RepositoryRoot $fixture } 'clean tracked source'
    [IO.File]::WriteAllText($sourcePath, $sourceText, [Text.UTF8Encoding]::new($false))
    $badPlan = [ordered]@{}
    foreach ($key in $plans[0].Keys) { $badPlan[$key] = $plans[0][$key] }
    $badPlan.sourceSha256 = '0' * 64
    Assert-FormattingFailure { Write-SharpProofCSharpFormattingReceipt -RepositoryRoot $fixture -Plan $badPlan } 'changed during verification'
    Assert-SharpProofCSharpFormattingShards -RepositoryRoot $fixture
    Write-Host 'C# formatting shard controls passed: complete roots/files, source/run binding, tampering, failed modes, and mixed successful attempts.'
}
finally {
    foreach ($name in $savedEnvironment.Keys) { [Environment]::SetEnvironmentVariable($name, $savedEnvironment[$name]) }
    if (Test-Path -LiteralPath $fixture) { Remove-Item -LiteralPath $fixture -Recurse -Force }
}
